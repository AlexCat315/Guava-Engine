public enum DestructionCause: String, Sendable, Equatable {
    case forced
    case damage
    case contactImpulse
    case connectionBreak
}

public struct DestructionEvent: Sendable, Equatable {
    public var sourceEntity: EntityID
    public var cause: DestructionCause
    public var fragmentEntities: [EntityID]
    public var fragmentIDs: [UInt32]
    public var brokenConnectionIDs: [UInt32]
    public var appliedDamage: Float
    public var appliedImpulse: Float
    public var droppedFragmentCount: Int

    public init(
        sourceEntity: EntityID,
        cause: DestructionCause,
        fragmentEntities: [EntityID],
        fragmentIDs: [UInt32],
        brokenConnectionIDs: [UInt32],
        appliedDamage: Float,
        appliedImpulse: Float,
        droppedFragmentCount: Int = 0
    ) {
        self.sourceEntity = sourceEntity
        self.cause = cause
        self.fragmentEntities = fragmentEntities
        self.fragmentIDs = fragmentIDs
        self.brokenConnectionIDs = brokenConnectionIDs
        self.appliedDamage = appliedDamage
        self.appliedImpulse = appliedImpulse
        self.droppedFragmentCount = max(0, droppedFragmentCount)
    }
}

public enum DestructionFailureReason: String, Sendable, Equatable {
    case invalidConfiguration
    case invalidCommand
