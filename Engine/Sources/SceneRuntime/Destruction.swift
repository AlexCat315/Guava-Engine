import Foundation
import SIMDCompat

/// Authored settings for an entity backed by a pre-fractured asset.
public struct Destructible: RuntimeComponent, Sendable, Equatable {
    public var assetResourceID: String
    public var damageThreshold: Float
    public var impulseThreshold: Float
    public var fragmentBudget: Int
    public var maximumFragmentLifetimeSeconds: Float
    public var sleepingRecycleDelaySeconds: Float
    public var separationImpulse: Float
    public var isEnabled: Bool

    public init(
        assetResourceID: String = "",
        damageThreshold: Float = 100,
        impulseThreshold: Float = 10,
        fragmentBudget: Int = 256,
        maximumFragmentLifetimeSeconds: Float = 30,
        sleepingRecycleDelaySeconds: Float = 5,
        separationImpulse: Float = 0.05,
        isEnabled: Bool = true
    ) {
        self.assetResourceID = assetResourceID
        self.damageThreshold = max(0, damageThreshold)
        self.impulseThreshold = max(0, impulseThreshold)
        self.fragmentBudget = max(0, fragmentBudget)
        self.maximumFragmentLifetimeSeconds = max(0, maximumFragmentLifetimeSeconds)
        self.sleepingRecycleDelaySeconds = max(0, sleepingRecycleDelaySeconds)
        self.separationImpulse = max(0, separationImpulse)
        self.isEnabled = isEnabled
    }
}

/// One convex piece generated by the pre-fracture asset pipeline.
public struct DestructibleFragmentAsset: Sendable, Equatable {
    public var fragmentID: UInt32
    public var colliderResourceID: String
    public var localTransform: LocalTransform
    public var mass: Float
    public var renderMesh: RenderMeshComponent?
    public var renderMaterial: RenderMaterialComponent?

    public init(
        fragmentID: UInt32,
        colliderResourceID: String,
        localTransform: LocalTransform = .identity,
        mass: Float = 1,
        renderMesh: RenderMeshComponent? = nil,
        renderMaterial: RenderMaterialComponent? = nil
    ) {
        self.fragmentID = fragmentID
        self.colliderResourceID = colliderResourceID
        self.localTransform = localTransform
        self.mass = max(0.0001, mass)
        self.renderMesh = renderMesh
        self.renderMaterial = renderMaterial
    }
}

/// A breakable edge in the imported fragment connection graph. A zero threshold
/// inherits the corresponding entity-level threshold from `Destructible`.
public struct DestructibleConnectionAsset: Sendable, Equatable {
    public var connectionID: UInt32
    public var fragmentA: UInt32
    public var fragmentB: UInt32
    public var damageThreshold: Float
    public var impulseThreshold: Float

    public init(
        connectionID: UInt32,
        fragmentA: UInt32,
        fragmentB: UInt32,
        damageThreshold: Float = 0,
        impulseThreshold: Float = 0
    ) {
        self.connectionID = connectionID
        self.fragmentA = fragmentA
        self.fragmentB = fragmentB
        self.damageThreshold = max(0, damageThreshold)
        self.impulseThreshold = max(0, impulseThreshold)
    }
}

/// Runtime-ready product of pre-fracture import. Convex geometry is resolved through
/// `MeshColliderGeometryResource`, so it shares the normal shape bake cache.
public struct DestructibleAsset: Sendable, Equatable {
    public var revision: UInt64
    public var fragments: [DestructibleFragmentAsset]
    public var connections: [DestructibleConnectionAsset]

    public init(
        revision: UInt64 = 0,
        fragments: [DestructibleFragmentAsset],
        connections: [DestructibleConnectionAsset] = []
    ) {
        self.revision = revision
        self.fragments = fragments.sorted { $0.fragmentID < $1.fragmentID }
        self.connections = connections.sorted { $0.connectionID < $1.connectionID }
    }
}

public struct DestructibleAssetResource: Sendable, Equatable {
    public var assetsByResourceID: [String: DestructibleAsset]

    public init(assetsByResourceID: [String: DestructibleAsset] = [:]) {
        self.assetsByResourceID = assetsByResourceID
    }

    public func asset(for resourceID: String) -> DestructibleAsset? {
        assetsByResourceID[resourceID]
    }
}

