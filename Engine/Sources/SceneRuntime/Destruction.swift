public struct DestructionSourceState: Sendable, Equatable {
    public var sourceEntity: EntityID
    public var hasFractured: Bool
    public var accumulatedDamage: Float
    public var brokenConnectionIDs: [UInt32]
    public var activeFragmentEntities: [EntityID]
    public var activeFragmentIDs: [UInt32]

    public init(
        sourceEntity: EntityID,
        hasFractured: Bool = false,
        accumulatedDamage: Float = 0,
        brokenConnectionIDs: [UInt32] = [],
        activeFragmentEntities: [EntityID] = [],
        activeFragmentIDs: [UInt32] = []
    ) {
        self.sourceEntity = sourceEntity
        self.hasFractured = hasFractured
        self.accumulatedDamage = accumulatedDamage
        self.brokenConnectionIDs = brokenConnectionIDs
        self.activeFragmentEntities = activeFragmentEntities
        self.activeFragmentIDs = activeFragmentIDs
    }
}

public struct DestructionStateFrameResource: Sendable, Equatable {
    public var sources: [EntityID: DestructionSourceState]

    public init(sources: [EntityID: DestructionSourceState] = [:]) {
        self.sources = sources
    }

    public var activeFragmentCount: Int {
        sources.values.reduce(0) { $0 + $1.activeFragmentEntities.count }
    }

    public static let empty = DestructionStateFrameResource()
}

/// Runtime ownership marker. Authored Scene and Prefab documents omit fragment
/// entities, while GameSave snapshots preserve this ownership with remapped IDs.
public struct DestructibleFragment: RuntimeComponent, Sendable, Equatable {
    public var sourceEntity: EntityID
    public var fragmentID: UInt32
    public var spawnedAtSeconds: Double
    public var maximumLifetimeSeconds: Float
    public var sleepingRecycleDelaySeconds: Float

    public init(
        sourceEntity: EntityID,
        fragmentID: UInt32,
        spawnedAtSeconds: Double,
        maximumLifetimeSeconds: Float,
        sleepingRecycleDelaySeconds: Float
    ) {
        self.sourceEntity = sourceEntity
        self.fragmentID = fragmentID
        self.spawnedAtSeconds = spawnedAtSeconds
        self.maximumLifetimeSeconds = max(0, maximumLifetimeSeconds)
        self.sleepingRecycleDelaySeconds = max(0, sleepingRecycleDelaySeconds)
    }
}

